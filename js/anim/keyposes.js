export async function render(ctx, arg, W, H) {
  const id = arg || 'S03', keys = KEYS[id], mod = await import(MOD[id]);
  const cols = 4, tw = W / cols, th = tw * 9 / 16, lh = 64;
  ctx.fillStyle = '#f2ece2'; ctx.fillRect(0, 0, W, H);
  const off = new OffscreenCanvas(1280, 720), ox = off.getContext('2d');
  for (let i = 0; i < keys.length; i++) {
    const [t, note] = keys[i], x = (i % cols) * tw, y = Math.floor(i / cols) * (th + lh);
    ox.setTransform(1, 0, 0, 1, 0, 0); ox.clearRect(0, 0, 1280, 720);
    await mod.renderFrame(ox, t, 1280, 720);
    ctx.drawImage(off, x + 6, y + 6, tw - 12, th - 12);
    ctx.fillStyle = '#2b211c'; ctx.font = '24px "Noto Sans SC"';
    ctx.fillText(`${id}  第 ${Math.round(t * 24)} 帧（${t.toFixed(2)} 秒）`, x + 12, y + th + 22);
    ctx.font = '20px "Noto Sans SC"'; ctx.fillStyle = '#5a4a40'; ctx.fillText(note, x + 12, y + th + 50);
  }
}
