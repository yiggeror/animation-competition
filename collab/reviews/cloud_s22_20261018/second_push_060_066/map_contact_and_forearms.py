#!/usr/bin/env python3
"""Map the locked drawn contact group to exposure displacement; reconnect the
newly generated forearm artwork with anchored entries and continuous profiles.
This resamples real drawings; no character is generated by code, no whole-sheet
translation is used as a production frame. Originals remain untouched.
"""
from pathlib import Path
import hashlib,json,sys,csv
import numpy as np
from PIL import Image,ImageDraw,ImageFont
from scipy import ndimage as nd
from scipy.signal import fftconvolve

HERE=Path(__file__).resolve().parent;ROOT=HERE.parent
LOCK=ROOT/'contact_band_repair_012_018_024/candidate/F024_contact_fixed.png'
assert hashlib.sha256(LOCK.read_bytes()).hexdigest()=='97560237598d024a725ab63ee62809d1f5ded5f6fc5aadc1d8a4f158ca85da4a'
base=np.array(Image.open(LOCK).convert('RGBA'));h,w=base.shape[:2];yy,xx=np.mgrid[:h,:w]
NAME=sys.argv[1] if len(sys.argv)>1 else 'F060'
row=next(r for r in csv.DictReader((ROOT/'S22_exposure.csv').open()) if int(r['start_frame'])==int(NAME[1:]))
world=np.array([float(row['shared_dx']),float(row['shared_dy'])]);ideal=world*1672/1920
DX,DY=map(int,np.rint(ideal))
assert (DX,DY)=={'F060':(37,-21),'F066':(49,-28)}[NAME]
P=HERE/NAME;meta=json.loads((P/'provenance/call01_output.json').read_text());rawpath=ROOT/meta['retained_raw'];raw=np.array(Image.open(rawpath).convert('RGBA'))
assert hashlib.sha256(rawpath.read_bytes()).hexdigest()==meta['sha256']
native_raw_size=[raw.shape[1],raw.shape[0]]
assert raw.shape[0]==h and raw.shape[2]==4 and abs(raw.shape[1]-w)<=1
right_pad=max(0,w-raw.shape[1])
if right_pad:raw=np.pad(raw,((0,0),(0,right_pad),(0,0)),mode='constant')
raw=raw[:,:w]
for sub in ['candidate','qa','masks']:(P/sub).mkdir(exist_ok=True)

def gray(a):
 alpha=a[:,:,3:4]/255;return (a[:,:,:3]*alpha+115*(1-alpha))@np.array([.299,.587,.114])
matches={};b=gray(base);r=gray(raw)
for label,(x0,y0,x1,y1) in {'child_thumbnail':[846,506,879,541],'adult_thumbnail':[702,544,734,576],'child_wrist_crease':[655,640,690,674],'child_palm_crease':[710,595,755,625]}.items():
 t=b[y0:y1,x0:x1];z=t-t.mean();search=r[max(0,y0-110):y1+70,x0-25:x1+200];n=z.size;ones=np.ones(t.shape)
 corr=fftconvolve(search,z[::-1,::-1],mode='valid');s=fftconvolve(search,ones,mode='valid');ss=fftconvolve(search**2,ones,mode='valid');score=corr/np.sqrt(np.maximum(ss-s*s/n,1e-9)*(z*z).sum());iy,ix=np.unravel_index(np.argmax(score),score.shape)
 matches[label]=dict(raw_delta=[int(ix-25),int(iy-110)],NCC=float(score[iy,ix]))
med=np.median(np.array([m['raw_delta'] for m in matches.values()]),axis=0);qx_offset=float(med[0]-DX)

def profiles(a,maxx):
 data=np.full((maxx+1,4),np.nan)
 for x in range(maxx+1):
  opaque=a[:,x,3]>=128;ls,n=nd.label(opaque);runs=[]
  for k in range(1,n+1):
   ys=np.where(ls==k)[0]
   if len(ys)>=15:runs.append((ys[0],ys[-1]))
  if len(runs)>=2:
   g,c=runs[0],runs[-1];data[x]=[g[0],g[1],c[0],c[1]]
 for k in range(4):
  valid=np.isfinite(data[:,k]);assert valid.sum()>100
  data[:,k]=np.interp(np.arange(maxx+1),np.where(valid)[0],data[valid,k])
 return data

# Whole hands/rod use the exact locked contact drawing at the table step.
target=np.zeros_like(base)
target[max(0,DY):h+min(0,DY),DX:w]=base[max(0,-DY):h-max(0,DY),0:w-DX]
END=520;START=400;max_source_x=min(w-1,int(END+abs(qx_offset)+20))
pbase=profiles(base,END);ptarget=profiles(target,END);praw=profiles(raw,max_source_x)
t=np.clip(np.arange(END+1)/END,0,1);t=t*t*(3-2*t)
desired=pbase*(1-t[:,None])+ptarget*t[:,None]
# A clipped lower arm continues offscreen rather than leaving a translated gap.
desired[pbase[:,3]>=h-2,3]=h-1
source_x=np.arange(END+1)+qx_offset*t
source_profiles=np.stack([np.interp(source_x,np.arange(max_source_x+1),praw[:,k]) for k in range(4)],1)
mapx=xx.astype(float);mapy=yy.astype(float)
for x in range(END+1):
 q=source_profiles[x];d=desired[x]
 # Pixel boundaries, including the gap, map continuously between both arms.
 sy=np.array([0,q[0],q[1],q[2],q[3],h-1],float)
 dy=np.array([0,d[0],d[1],d[2],d[3],h-1],float)
 keep=np.r_[True,np.diff(dy)>1e-6]
 mapy[:,x]=np.interp(np.arange(h),dy[keep],sy[keep]);mapx[:,x]=source_x[x]
coords=[mapy,mapx];warped=np.stack([nd.map_coordinates(raw[:,:,k].astype(float),coords,order=1,mode='nearest') for k in range(4)],2)
weight=np.clip((xx-START)/(END-START),0,1);weight=weight*weight*(3-2*weight)
ar=warped[:,:,3:4]/255;at=target[:,:,3:4]/255;z=weight[:,:,None];alpha=ar*(1-z)+at*z
rgb=np.divide(warped[:,:,:3]*ar*(1-z)+target[:,:,:3]*at*z,alpha,out=np.zeros_like(warped[:,:,:3]),where=alpha>0)
out=np.rint(np.concatenate([rgb,alpha*255],2)).clip(0,255).astype('uint8');out[:,END:]=target[:,END:]
# Where the lower forearm continues through the bottom crop, do not expose the
# raw's formerly visible bottom contour as a horizontal cut line in the frame.
continued=0
for x in range(END):
 if base[h-1,x,3]>=128 and base[h-1,x,0]>210 and desired[x,3]>=h-2:
  donor=out[h-10,x].copy()
  if donor[3]>=128 and donor[0]>210:
   for y in range(h-6,h):
    z=(y-(h-6))/5;out[y,x]=np.rint(out[y,x]*(1-z)+donor*z).astype('uint8')
   continued+=1
path=P/'candidate'/f'{NAME}_mapped.png';Image.fromarray(out).save(path)
# One rigid contact group, including nails, creases, contact shadow and shaft.
boxes={'child_pinch':[760,470,893,566],'child_wrist':[655,640,690,674],'adult_thumb':[690,530,746,590],'four_supporting_ends':[665,580,902,742],'single_rod':[950,0,1672-DX,510]}
proof={}
for label,(x0,y0,x1,y1) in boxes.items():
 y0=max(y0,-DY);x1=min(x1,w-DX)
 src=base[y0:y1,x0:x1];dst=out[y0+DY:y1+DY,x0+DX:x1+DX];m=src[:,:,3]>=128;delta=np.abs(src.astype(int)-dst.astype(int))[m]
 assert not np.any(delta),(NAME,label);proof[label]=dict(source_box=[x0,y0,x1,y1],native_delta=[DX,DY],visible_pixels=int(m.sum()),max_RGBA_error=0)
for label,a in [('locked024',base),('mapped',out)]:
 ls,n=nd.label(a[:,4,3]>=128);runs=[]
 for k in range(1,n+1):
  ys=np.where(ls==k)[0]
  if len(ys)>=15:runs.append([int(ys[0]),int(ys[-1])])
 proof[label+'_left_entries']=runs
for kind,color in [('gray',(115,115,115)),('white',(255,255,255)),('black',(0,0,0))]:
 im=Image.fromarray(out);plate=Image.new('RGBA',im.size,(*color,255));plate.alpha_composite(im);plate.convert('RGB').save(P/'qa'/f'{NAME}_mapped_on_{kind}.png')
Image.open(P/'qa'/f'{NAME}_mapped_on_gray.png').crop((470,340,1000,755)).resize((1060,830)).save(P/'qa'/f'{NAME}_mapped_contact_2x.png')
Image.fromarray(np.rint(weight*255).astype('uint8')).save(P/'masks/contact_group_blend.png')
np.savez_compressed(P/'provenance/forearm_map.npz',source_x=source_x,source_profiles=source_profiles,target_profiles=desired)
record=dict(locked_F024_sha256=hashlib.sha256(LOCK.read_bytes()).hexdigest(),raw_sha256=meta['sha256'],native_raw_size=native_raw_size,right_transparent_pad_columns=right_pad,mapped_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),raw_anchor_matches=matches,median_raw_delta=med.tolist(),native_table_delta=[DX,DY],uniform_ideal_delta=ideal.tolist(),world_cumulative_delta=world.tolist(),calculation_origin='locked F024; cumulative rounding from world table',method='Locked drawn hand/rod group rigidly mapped; newly image-generated forearm pixels remapped with fixed left entries and continuous arm profiles into advancing wrist roots. Not a whole-sheet translation.',forearm_join_x=[START,END],offscreen_lower_arm_continuation_columns=continued,proof=proof,new_image_calls_for_mapping=0)
(P/'provenance/mapping_checks.json').write_text(json.dumps(record,indent=2)+'\n');print(json.dumps(record,indent=2))
