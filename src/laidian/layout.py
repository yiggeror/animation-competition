"""堂屋平面布局：全片唯一的空间数据来源。

坐标单位：米。原点在堂屋室内西南角的地面。
x 向东，y 向北，z 向上。
平面图、渲染、镜头都从这里取数，保证不同镜头里门窗、家具、光源的位置一致。
"""
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Box:
    """轴对齐的长方体（家具、墙洞等）。"""
    name: str
    x0: float
    x1: float
    y0: float
    y1: float
    z0: float = 0.0
    z1: float = 0.0
    label: str = ""

    @property
    def center(self):
        return ((self.x0 + self.x1) / 2, (self.y0 + self.y1) / 2, (self.z0 + self.z1) / 2)


@dataclass(frozen=True)
class Point:
    name: str
    x: float
    y: float
    z: float
    label: str = ""


