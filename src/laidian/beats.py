def timeline():
    """返回 [(beat, start, end)]。"""
    t = 0.0
    out = []
    for b in BEATS:
        out.append((b, t, t + b.dur))
        t += b.dur
    return out


def total_duration():
    return sum(b.dur for b in BEATS) + CREDITS_DUR
